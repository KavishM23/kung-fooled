// Checks obstacle behavior without rendering or relying on a particular route.
'use strict';
const assert = require('node:assert/strict'), vm = require('node:vm'), fs = require('node:fs'), path = require('node:path');
const root = path.join(__dirname, '..');
const sb = { console, Math, JSON, Object, Array, Set, Map, Uint8Array, Error, parseInt, Number };
sb.window = sb; vm.createContext(sb);
for (const file of ['core.js', 'physics.js', 'world.js', 'player.js', 'traps.js', 'combat.js', 'stage.js', 'rules.js', 'levels/doors.js'])
  vm.runInContext(fs.readFileSync(path.join(root, 'js', file), 'utf8'), sb, { filename: file });
for (const file of fs.readdirSync(path.join(root, 'js/levels')).filter((f) => /^world\d+\.js$/.test(f)).sort())
  vm.runInContext(fs.readFileSync(path.join(root, 'js/levels', file), 'utf8'), sb, { filename: file });
const KF = sb.KF, retro = KF.Doors.find((d) => d.id === 'oldtv');
const moving = new KF.Stage(retro.stages[0]).traps.find((t) => t.def.type === 'movingSpikes');
const start = moving.x;
moving.stage.t = moving.period / 4; moving.tick();
assert(moving.x > start + 20, 'spikes should move toward their patrol end');
let box = KF.spikeRect('up', moving.x, moving.y);
assert(moving.kills({ x: box.x, y: box.y, w: box.w, h: box.h }), 'moving spikes must damage on contact');
assert(!moving.kills({ x: 0, y: 0, w: 8, h: 8 }), 'moving spikes must not damage at a distance');
moving.stage.t = moving.period; moving.tick();
assert.equal(moving.x, start, 'moving spikes should return home');
const beam = new KF.Stage(retro.stages[1]).traps.find((t) => t.def.type === 'pulseBeam');
const target = { x: beam.rect.x, y: beam.rect.y + 15, w: beam.rect.w, h: 8 };
beam.stage.t = 0;
assert(beam.active && beam.kills(target), 'lit beam must damage on contact');
beam.stage.t = beam.on + 0.2;
assert(!beam.active && !beam.kills(target), 'beam must leave a safe timing window');
const arcade = KF.Doors.find((d) => d.id === 'arcade');
const belt = new KF.Stage(arcade.stages[0]).traps.find((t) => t.def.type === 'conveyor');
const rider = { x: belt.rect.x + 8, y: belt.rect.y + 4 - 26, w: 12, h: 26, grounded: true, gravDir: 1 };
assert.equal(belt.push(rider), 80, 'the belt must move a grounded player on its surface');
rider.y -= 8;
assert.equal(belt.push(rider), 0, 'the belt must not push a jumping player');
const pocket = KF.Doors.find((d) => d.id === 'pocket');
const reverseBelt = new KF.Stage(pocket.stages[0]).traps.find((t) => t.def.type === 'conveyor');
rider.x = reverseBelt.rect.x + 8; rider.y = reverseBelt.rect.y + 4 - 26;
assert.equal(reverseBelt.push(rider), -85, 'a reverse belt must oppose forward movement');
const comic = KF.Doors.find((d) => d.id === 'comic');
const launcher = new KF.Stage(comic.stages[1]).traps.find((t) => t.def.type === 'dartLauncher');
launcher.stage.t = launcher.period - launcher.def.offset + 0.05;
const dart = launcher.dart;
assert(dart && launcher.kills(dart), 'a fired dart must damage on contact');
assert(!launcher.kills({ x: 0, y: 0, w: 8, h: 8 }), 'the dart must not damage at a distance');
launcher.stage.t += launcher.range / launcher.speed + 0.1;
assert.equal(launcher.dart, null, 'the dart must stop after its stated range');
const lure = new KF.Stage(arcade.stages[1]).traps.find((t) => t.def.type === 'lureFloor');
for (const door of KF.Doors) for (const def of door.stages) for (const trap of (def.traps || []).filter((t) => t.type === 'lureFloor')) {
  const floor = new KF.Stage(def).traps.find((t) => t.def === trap);
  assert(floor.tiles.every(([, , id]) => id === 1), 'lure floors must replace solid ground tiles');
}
const walker = lure.stage.player;
walker.x = lure.rect.x - walker.w - 4; walker.y = lure.rect.y - walker.h;
lure.update(0.01);
assert.equal(lure.mode, 'warning', 'the floor must warn when approached');
assert(lure.solid.active, 'the floor must remain solid during its warning');
lure.update(lure.def.delay + 0.01);
assert.equal(lure.mode, 'gone', 'the floor must vanish after its warning');
assert(!lure.solid.active, 'vanished floor must stop supporting the player');
walker.x = 0; lure.update(lure.def.reform || 1.5);
assert(lure.solid.active, 'the floor must reform after the player leaves');
const retroSwing = new KF.Stage(retro.stages[2]).traps.find((t) => t.def.type === 'swingHammer');
const hammer = retroSwing.blade();
assert(retroSwing.kills(hammer), 'a swinging hammer must damage on contact');
retroSwing.stage.t = retroSwing.period / 4;
assert.notEqual(retroSwing.blade().x, hammer.x, 'the hammer must swing across its arc');
const saw = new KF.Stage(comic.stages[1]).traps.find((t) => t.def.type === 'lookSaw');
const targetPlayer = saw.stage.player;
targetPlayer.x = saw.home - 30; targetPlayer.facing = 1;
saw.tick(0.2);
assert.equal(saw.x, saw.home, 'looking at the saw must freeze it');
targetPlayer.facing = -1; saw.tick(0.2);
assert(saw.x < saw.home, 'looking away must let the saw creep closer');
assert(saw.kills(saw.body), 'the saw must damage on contact');
console.log('PASS patrol, beams, belts, darts, lure floor, swing hammer, and look-away saw');
