// stairs, floating blocks, underground rooms you reach by pipe, moving stones over lava, a
// fort and its tower. Every height change is a jump, a pipe, a spring or a lift, never a
// glass elevator or a rooftop scaffold. The tricks are the ones an old console would play:
// blocks that aren't there, a hidden block in your jump, the floor giving way into the cellar,
// a pipe that lies, a lift that doesn't stop.
// See KF.Families in js/levels/routes.js for the part format.
